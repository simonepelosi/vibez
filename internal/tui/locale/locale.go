// Package locale contains the application's fixed interface copy. Song metadata
// and command tokens remain untouched. Standard-library map lookup suffices:
// these labels need neither message extraction nor a general localization engine.
package locale

import "strings"

type Locale struct{ Language string }

func (l Locale) Text(s string) string {
	if strings.HasPrefix(strings.ToLower(l.Language), "zh") {
		if translated, ok := chinese[s]; ok {
			return translated
		}
	}
	return s
}

